"""Re-derive the feasibility--learning decomposition of the cooperative reward-gap
decline (paper Sec. 7.8, Table `tab:rjoint-decomp`; `RJOINT_FINDINGS.md`).

Provenance
----------
The reward gap of record is measured against the infeasible per-agent ideal
`R* = 0`. It splits as

    dR  =  (R* - R_joint)      +   (R_joint - Rbar)
           |__ F: feasibility __|    |__ L: learning __|
              floor >= 0                shortfall >= 0

where `R_joint` is the best achievable *mean* per-agent reward at a single shared
state in the box `[0, CAPACITY]^M`. Because the summed reward separates by resource,
the joint optimum is the closed-form stake-weighted average of targets, clipped:

    s*_j = clip( sum_i w_ij tau_ij / sum_i w_ij , 0, CAPACITY )
    r_i(s*) = - sum_j w_ij (s*_j - tau_ij)^2 ,   R_joint = mean_i r_i(s*).

F depends ONLY on the seeded preference draws (targets/weights), so it is identical
for IQL and VDN. L uses each run's trained `mean_reward` from the archived CSVs.

The preference draws are regenerated by replaying the EXACT seeded DGP path of
`results/adversarial_rerun/adv_runner.py`:

    master = default_rng(42)
    master.uniform(0, CAPACITY, size=(128, M))            # probe draw (advances master)
    cond_seeds = {(rho, sigma): master.integers(0, 2**62) # one per condition,
                  for rho in RHOS for sigma in SIGMAS}     # in rho-major, sigma-minor order
    # per condition: rng = default_rng(cond_seed); then, per replication,
    #   sample_agent_params_equicorr(rng, A, M, rho, sigma)  -> standard_normal targets,
    #                                                            then normal(sigma, 0.05) weights

so per-rep F is the feasibility floor of the SAME preference draw each RL run trained
on. This script imports the real DGP sampler (no re-implementation) to stay faithful.

Regenerates the committed artifacts and checks them against the paper:
    rjoint_conditions_{iql,vdn}.csv  (per-condition means)
    rjoint_decomposition_summary.csv (replication-level regression slopes)

Run:  python results/review2_jun27/rjoint_recompute.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd
import statsmodels.formula.api as smf

REPO = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
ADV = REPO / "results" / "adversarial_rerun"
sys.path.insert(0, str(REPO))

from results.adversarial_rerun.dgp import sample_agent_params_equicorr  # noqa: E402

# --- design constants: identical to adv_runner.py / b_vdn_runner.py defaults -------
N_AGENTS = 4
N_RESOURCES = 3
CAPACITY = 10.0
RHOS = [-0.33, -0.2, -0.1, 0.0, 0.2, 0.4, 0.6, 0.8]
SIGMAS = [0.6, 1.0]
N_REPS = 30
MASTER_SEED = 42


def regenerate_preferences() -> pd.DataFrame:
    """Replay the seeded DGP path; return per-(condition, replication) F, R_joint,
    and the box-clip / conflict split of F."""
    master = np.random.default_rng(MASTER_SEED)
    # probe draw: advances the master RNG exactly as adv_runner.py does before seeds
    master.uniform(0.0, CAPACITY, size=(128, N_RESOURCES)).astype(np.float32)
    cond_keys = [(rho, s) for rho in RHOS for s in SIGMAS]
    cond_seeds = {k: int(master.integers(0, 2**62)) for k in cond_keys}

    recs = []
    for (rho, sigma) in cond_keys:
        rng = np.random.default_rng(cond_seeds[(rho, sigma)])
        for rep in range(N_REPS):
            w, t = sample_agent_params_equicorr(rng, N_AGENTS, N_RESOURCES, rho, sigma)
            w = w.astype(np.float64)
            t = t.astype(np.float64)

            # closed-form joint optimum at a single shared state, clipped to the box
            s_star = np.clip((w * t).sum(axis=0) / w.sum(axis=0), 0.0, CAPACITY)  # (M,)
            r_i = -(w * (s_star[None, :] - t) ** 2).sum(axis=1)                   # (A,)
            r_joint = float(r_i.mean())
            F = -r_joint  # since R* = 0

            # split F = box-clip floor + shared-state conflict.
            # box-clip: each agent alone picks s_i = clip(tau_i, 0, C) per resource;
            # loss is nonzero only where a target falls outside the box.
            s_box = np.clip(t, 0.0, CAPACITY)                                     # (A,M)
            r_box_i = -(w * (s_box - t) ** 2).sum(axis=1)                         # (A,)
            F_box = float(-r_box_i.mean())
            F_conflict = F - F_box

            recs.append(dict(rho=rho, sigma=sigma, replication=rep,
                             rjoint=r_joint, F=F, F_box=F_box, F_conflict=F_conflict))
    return pd.DataFrame(recs)


def regress(df: pd.DataFrame, col: str):
    m = smf.ols(f"{col} ~ rho", data=df).fit()
    return float(m.params["rho"]), float(m.pvalues["rho"]), float(m.rsquared)


def build(learner: str, csv_name: str, prefs: pd.DataFrame):
    d = pd.read_csv(ADV / csv_name)[["rho", "sigma", "replication", "mean_reward"]]
    m = prefs.merge(d, on=["rho", "sigma", "replication"], how="inner")
    assert len(m) == len(RHOS) * len(SIGMAS) * N_REPS, (learner, len(m))

    m["Rbar"] = m["mean_reward"]
    m["gap"] = -m["Rbar"]                 # dR = R* - Rbar = -Rbar
    m["L"] = m["rjoint"] - m["Rbar"]      # learning shortfall >= 0
    for c in ["gap", "F", "L", "F_box", "F_conflict"]:
        m[c + "_norm"] = m[c] / m["sigma"]

    # replication-level regressions (n = 480), sigma-normalized (matches slope of record)
    sg, pg, r2g = regress(m, "gap_norm")
    sF, pF, r2F = regress(m, "F_norm")
    sL, pL, r2L = regress(m, "L_norm")
    sbox, pbox, r2box = regress(m, "F_box_norm")
    scon, pcon, r2con = regress(m, "F_conflict_norm")

    # raw-unit versions (no sigma normalization)
    sg_r, _, _ = regress(m, "gap")
    sF_r, pF_r, _ = regress(m, "F")
    sL_r, pL_r, r2L_r = regress(m, "L")

    summary = dict(
        learner=learner,
        slope_gap_norm=sg, slope_F_norm=sF, p_F_norm=pF, r2_F_norm=r2F,
        slope_L_norm=sL, p_L_norm=pL, r2_L_norm=r2L,
        feas_share_norm=sF / sg, learn_share_norm=sL / sg,
        slope_gap_raw=sg_r, slope_F_raw=sF_r, p_F_raw=pF_r,
        slope_L_raw=sL_r, p_L_raw=pL_r, r2_L_raw=r2L_r,
        feas_share_raw=sF_r / sg_r, learn_share_raw=sL_r / sg_r,
        decomp_max_abs_err=float((m["F"] + m["L"] - m["gap"]).abs().max()),
        min_L=float(m["L"].min()),
    )

    # per-condition means (the rjoint_conditions_*.csv artifact)
    cond = (m.groupby(["rho", "sigma"], as_index=False)
              .agg(gap=("gap", "mean"), F=("F", "mean"), L=("L", "mean"),
                   rjoint=("rjoint", "mean")))
    cond["gap_norm"] = cond["gap"] / cond["sigma"]
    cond["F_norm"] = cond["F"] / cond["sigma"]
    cond["L_norm"] = cond["L"] / cond["sigma"]

    floor = dict(
        box_slope=sbox, box_p=pbox, box_mean=float(m["F_box_norm"].mean()),
        conflict_slope=scon, conflict_p=pcon, conflict_r2=r2con,
        conflict_mean=float(m["F_conflict_norm"].mean()),
    )
    return summary, cond, floor


def main():
    prefs = regenerate_preferences()

    # closed-form vs numeric optimum sanity check on a few draws
    from scipy.optimize import minimize
    rng = np.random.default_rng(0)
    max_err = 0.0
    for _ in range(200):
        w, t = sample_agent_params_equicorr(rng, N_AGENTS, N_RESOURCES, 0.3, 0.8)
        w = w.astype(np.float64); t = t.astype(np.float64)
        s_cf = np.clip((w * t).sum(0) / w.sum(0), 0.0, CAPACITY)
        obj = lambda s: -(-(w * (s[None, :] - t) ** 2).sum(1)).mean()  # noqa: E731
        res = minimize(obj, x0=np.full(N_RESOURCES, CAPACITY / 2),
                       bounds=[(0, CAPACITY)] * N_RESOURCES, method="L-BFGS-B",
                       options={"ftol": 1e-15, "gtol": 1e-12})
        max_err = max(max_err, float(np.abs(s_cf - res.x).max()))
    print(f"closed-form vs numeric optimum: max|s* diff| = {max_err:.2e}\n")

    summaries, conds = [], {}
    print(f"{'':6} {'slope_gap':>10} {'slope_F':>10} {'p_F':>10} "
          f"{'slope_L':>10} {'p_L':>10} {'feas%':>8} {'learn%':>8}")
    for learner, csv in [("IQL", "equicorr_iql.csv"), ("VDN", "equicorr_vdn.csv")]:
        s, cond, floor = build(learner, csv, prefs)
        summaries.append(s)
        conds[learner] = cond
        print(f"{learner:6} {s['slope_gap_norm']:10.4f} {s['slope_F_norm']:10.4f} "
              f"{s['p_F_norm']:10.2e} {s['slope_L_norm']:10.4f} {s['p_L_norm']:10.2e} "
              f"{100*s['feas_share_norm']:7.1f}% {100*s['learn_share_norm']:7.1f}%")
        print(f"       floor split: box slope={floor['box_slope']:+.4f} "
              f"(p={floor['box_p']:.2f}, mean={floor['box_mean']:.3f}) | "
              f"conflict slope={floor['conflict_slope']:+.4f} "
              f"(p={floor['conflict_p']:.1e}, R2={floor['conflict_r2']:.3f}, "
              f"mean={floor['conflict_mean']:.3f})")
        print(f"       decomp max|F+L-dR|={s['decomp_max_abs_err']:.1e}  "
              f"min L={s['min_L']:+.4f}")

    out_summary = pd.DataFrame(summaries)

    # ---- verification against the committed artifacts -----------------------------
    print("\n=== VERIFICATION vs committed rjoint_decomposition_summary.csv ===")
    ref = pd.read_csv(HERE / "rjoint_decomposition_summary.csv").set_index("learner")
    cur = out_summary.set_index("learner")
    cols = ["slope_gap_norm", "slope_F_norm", "p_F_norm", "slope_L_norm",
            "p_L_norm", "feas_share_norm", "learn_share_norm"]
    ok = True
    for learner in ["IQL", "VDN"]:
        for c in cols:
            a, b = cur.loc[learner, c], ref.loc[learner, c]
            rel = abs(a - b) / (abs(b) + 1e-12)
            flag = "" if rel < 1e-6 else "  <-- MISMATCH"
            if rel >= 1e-6:
                ok = False
            print(f"  {learner} {c:20} recomputed={a:+.6g}  committed={b:+.6g}{flag}")
    print("\nAll summary values reproduce to <1e-6 relative error." if ok
          else "\n*** MISMATCH: recomputed values diverge from committed CSV ***")

    if "--write" in sys.argv:
        out_summary.to_csv(HERE / "rjoint_decomposition_summary.csv", index=False)
        for learner in ["IQL", "VDN"]:
            conds[learner][["rho", "sigma", "gap", "F", "L", "rjoint",
                            "gap_norm", "F_norm", "L_norm"]].to_csv(
                HERE / f"rjoint_conditions_{learner.lower()}.csv", index=False)
        print("\n(--write) artifacts rewritten.")


if __name__ == "__main__":
    main()
